export const STRINGS: Record<Lang, Record<TKey, string>> = { ru, en };

/** Подставляет значения вида {n} в строку перевода. */
export function f(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? ""));
}

export function formatNumber(value: number, lang: Lang): string {
  return value.toLocaleString(lang === "ru" ? "ru-RU" : "en-US");
}

export function getExplorerRank(solvedCount: number, lang: Lang): string {
  const t = STRINGS[lang];
  if (solvedCount >= 40) return t.rank5;
  if (solvedCount >= 25) return t.rank4;
  if (solvedCount >= 12) return t.rank3;
  if (solvedCount >= 4) return t.rank2;
  return t.rank1;
}
